"""Export local wake-word templates and 20 kHz analysis tables to flash."""
import argparse
from pathlib import Path
import sys

import numpy as np

root = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(root / 'server/scripts'))
import wakeword

parser = argparse.ArgumentParser(description=__doc__, fromfile_prefix_chars='@')
parser.add_argument('--reference', dest='inputs', action='append',
                    type=lambda path: (Path(path), False), help='isolated word WAV')
parser.add_argument('--trimmed-reference', dest='inputs', action='append',
                    type=lambda path: (Path(path), True), help='already-trimmed WAV')
local = root / 'firmware/.local'
args = parser.parse_args(sys.argv[1:] or ['@' + str(local / 'wakeword-references.txt')])
if len(args.inputs or []) < 2:
    parser.error('supply two or more reference WAVs')
templates = [wakeword.features(path)[0] if trimmed else wakeword.template(path)
             for path, trimmed in args.inputs]

lengths = [len(t) for t in templates]
lines = ['// Generated by firmware/scripts/export-wakeword.py.',
         f'enum {{ TEMPLATE_FRAMES = {sum(lengths)}, TEMPLATE_COUNT = {len(lengths)} }};']


def table(name, data, integer=False):
    values = np.asarray(data).flatten()
    lines.append(f'static const {"unsigned short" if integer else "float"} {name}[] = {{')
    for start in range(0, len(values), 8):
        row = values[start:start + 8]
        lines.append('    ' + ', '.join(str(int(v)) if integer else f'{v:.8e}f' for v in row) + ',')
    lines.append('};')


table('template_lengths', lengths, True)
table('template_vectors', np.concatenate(templates))
table('hann', np.hanning(500))
table('fft_cos', np.cos(2 * np.pi * np.arange(500) / 500))
table('fft_sin', -np.sin(2 * np.pi * np.arange(500) / 500))
table('dct', np.cos(np.pi / 32 * (np.arange(32)[:, None] + .5) * np.arange(1, 14)).T)
edges = 700 * np.expm1(np.linspace(np.log1p(120 / 700), np.log1p(7600 / 700), 34))
freq = np.arange(251) * 40
starts, counts, weights = [], [], []
for a, b, c in zip(edges, edges[1:], edges[2:]):
    band = np.maximum(0, np.minimum((freq-a)/(b-a), (c-freq)/(c-b)))
    bins = np.flatnonzero(band)
    starts.append(bins[0])
    counts.append(len(bins))
    weights.extend(band[bins])
table('mel_start', starts, True)
table('mel_count', counts, True)
table('mel_weights', weights)
local.mkdir(mode=0o700, exist_ok=True)
(local / 'wakeword_model.inc').write_text('\n'.join(lines) + '\n')
